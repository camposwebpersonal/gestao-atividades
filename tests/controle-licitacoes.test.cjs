const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');

let source=fs.readFileSync(require('node:path').join(__dirname,'../js/controle-licitacoes.js'),'utf8');
source=source.replace(/import .*;\n/,'');
const context={window:{S:{items:[],subitems:[],secs:[]}},navigator:{onLine:true},console,document:{}};
vm.createContext(context);vm.runInContext(source,context);
const api=context.window.__licitacaoTest;

assert.equal(api.isLicitacaoGroup({name:'Licitação'}),true);
assert.equal(api.isLicitacaoGroup({name:'LICITACAO'}),true);
assert.equal(api.isLicitacaoGroup({name:'Outros',extra_fields:{controle_licitacoes:1}}),true);
assert.equal(api.isLicitacaoGroup({name:'Perfuração de poços'}),false);
assert.deepEqual(Array.from(api.SEED_GROUPS),['FUNDO GERAL','SEC. EDUCAÇÃO','SEC. SAÚDE','SEC. ASSISTÊNCIA SOCIAL']);
assert.deepEqual(Array.from(api.COLUMNS,x=>x.label),['N° PROCESSO','MODALIDADE','OBJETO','FORNECEDOR / N°','CONTRATO','VALOR GLOBAL','VIGÊNCIA','OBS']);
assert.deepEqual(Array.from(api.REQUEST_COLUMNS,x=>x.label),['DATA','OBJETO','SECRETARIA','OBS']);
assert.deepEqual(Array.from(api.templateForName('Solicitação de Licitações'),x=>x.label),['DATA','OBJETO','SECRETARIA','OBS']);
assert.deepEqual(Array.from(api.templateForName('Fundo Geral'),x=>x.label),['N° PROCESSO','MODALIDADE','OBJETO','FORNECEDOR / N°','CONTRATO','VALOR GLOBAL','VIGÊNCIA','OBS']);
assert.match(api.rowStatusBadges(['PENDENTE','RESSALVA']),/PENDENTE/);
assert.match(api.rowStatusBadges(['PENDENTE','RESSALVA']),/RESSALVA/);
assert.match(api.rowStatusBadges([]),/SELECIONAR STATUS/);
assert.equal(typeof context.window.openLicitacaoColumns,'function');
assert.equal(typeof context.window.addLicitacaoColumn,'function');
assert.equal(typeof context.window.saveLicitacaoColumns,'function');
assert.equal(typeof context.window.gerarPdfLicitacoes,'function');
assert.equal(typeof context.window.openLicitacaoStatusOrder,'function');
assert.equal(typeof context.window.addLicitacaoStatusOption,'function');
assert.equal(typeof context.window.removeLicitacaoStatusOption,'function');
assert.equal(typeof context.window.moveLicitacaoStatus,'function');
assert.equal(typeof context.window.saveLicitacaoStatusOrder,'function');
assert.equal(api.STATUSES.includes('RESSALVA'),true);
assert.deepEqual(Array.from(api.statusOrderFor({status_options:['RESSALVA','URGENTE']})),['RESSALVA','URGENTE']);
assert.deepEqual(Array.from(api.statusOrderFor({})),Array.from(api.STATUSES));
assert.deepEqual(Array.from(api.uniqueStatuses([' urgente ','URGENTE','Aguardando parecer'])),['URGENTE','AGUARDANDO PARECER']);
assert.deepEqual(Array.from(api.statuses({registro_tipo:'licitacao_grupo',status_options:['URGENTE','RESSALVA'],status_list:['RESSALVA','URGENTE']})),['URGENTE','RESSALVA']);
assert.deepEqual(Array.from(api.statusesForOptions({status_list:['PENDENTE','RESSALVA']},['RESSALVA'])),['RESSALVA']);
assert.equal(api.money('R$ 1.234.567,89'),1234567.89);
assert.equal(api.money('7000,50'),7000.5);
assert.equal(api.money(''),null);
assert.equal(api.dateISO('22/10/2026'),'2026-10-22');
assert.equal(api.dateISO('2026-10-22'),'2026-10-22');
assert.equal(api.dateISO('31/02/2026'),null);
assert.equal(api.dateBR('2026-10-22'),'22/10/2026');
assert.equal(api.dateBR('22/10/2026'),'22/10/2026');
assert.equal(api.pdfCell({data:'2026-10-22'},{key:'data',type:'date'}),'22/10/2026');
assert.match(api.pdfCell({valor_global:'1.234,50'},{key:'valor_global',type:'currency'}),/1\.234,50/);
assert.match(source,/RELATÓRIO DE LICITAÇÕES/);
assert.match(source,/Gerar PDF deste grupo/);
assert.match(source,/Gerenciar itens de status/);
assert.match(source,/status_options:order/);
assert.match(source,/Criar status/);
assert.match(source,/retirado dos lançamentos que o utilizam/);
assert.match(source,/placeholder="dd\/mm\/yyyy"/);
assert.match(source,/Use o formato DD\/MM\/YYYY/);
assert.equal(typeof api.closeLicitacaoStatusMenus,'function');
const insideTarget={};
let outsideClosed=false,insideClosed=false;
context.document.querySelectorAll=()=>[
  {contains:()=>false,removeAttribute:name=>{if(name==='open')outsideClosed=true;}},
  {contains:target=>target===insideTarget,removeAttribute:name=>{if(name==='open')insideClosed=true;}}
];
api.closeLicitacaoStatusMenus({target:insideTarget});
assert.equal(outsideClosed,true);
assert.equal(insideClosed,false);
api.closeLicitacaoStatusMenus();
assert.equal(insideClosed,true);
assert.match(source,/addEventListener\?\.\('pointerdown',closeLicitacaoStatusMenus\)/);
assert.match(source,/event\.key==='Escape'/);
console.log('controle-licitacoes: estrutura, colunas, ordem de status, valores e PDF validados');
